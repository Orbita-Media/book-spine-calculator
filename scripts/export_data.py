"""Export the print specifications of ShelfPublisher for the calculator.

Reads the catalogue that the ShelfPublisher portal uses for its own cover
templates and upload checks (app/services/formats.py in the Publishing
Platform repo) and writes:

  docs/data.js            - the data for the web page
  extension/data.js       - the same data for the Chrome extension
  tests/vectors.json      - reference results computed by the portal itself

    python scripts/export_data.py [path-to-publishing-platform]
"""
from __future__ import annotations

import datetime as dt
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PLATFORM = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(
    r"C:\Users\nmdar\Nextcloud\TOOLS\Publishing Platform")
sys.path.insert(0, str(PLATFORM))

from app.services import formats as F  # noqa: E402

CHANNEL_LABEL = {F.CHANNEL_INGRAM: "International print", F.CHANNEL_BOD: "European print"}
CHANNEL_LABEL_DE = {F.CHANNEL_INGRAM: "Internationaler Druck", F.CHANNEL_BOD: "Europäischer Druck"}
PAPER_LABEL_DE = {
    "international_white_50": "Weiß 50 lb / 74 g/m²",
    "international_cream_50": "Creme 50 lb / 74 g/m²",
    "europa_white_90": "Weiß 90 g/m²",
    "europa_cream_90": "Creme 90 g/m²",
}


def f(x) -> float:
    return float(x)


def main() -> None:
    papers = [p for p in F.PAPERS if p.angeboten]
    formats = [fm for fm in F.FORMATS if fm.angeboten]
    data = {
        "updated": dt.date.today().isoformat(),
        "source": "ShelfPublisher print specifications (shelfpublisher.com)",
        "channels": {},
        "papers": [],
        "formats": [],
        "spineTable": {str(k): v for k, v in F.SPINE_TABLE_INTERNATIONAL_WHITE_50.items()},
        "spineTableRange": [F._SPINE_TABLE_MIN, F._SPINE_TABLE_MAX],
        "spineSafety": {"thresholdMm": f(F.SPINE_SAFETY_THRESHOLD_MM), "wideMm": f(F.SPINE_SAFETY_WIDE_MM),
                        "narrowMm": f(F.SPINE_SAFETY_NARROW_MM)},
        "barcodeField": {"widthMm": f(F.barcode_field_mm()[0]), "heightMm": f(F.barcode_field_mm()[1]),
                         "marginSpineMm": f(F.BARCODE_MARGIN_SPINE_MM),
                         "marginBottomMm": f(F.BARCODE_MARGIN_BOTTOM_MM)},
    }
    for code in (F.CHANNEL_INGRAM, F.CHANNEL_BOD):
        spec = F.get_channel(code)
        data["channels"][code] = {
            "label": CHANNEL_LABEL[code], "labelDe": CHANNEL_LABEL_DE[code],
            "coverBleedMm": f(spec.cover_bleed_mm), "paperbackSpineExtraMm": f(spec.paperback_spine_extra_mm),
            "spineTextMinPages": spec.spine_text_min_pages, "safetyMm": f(F.cover_safety_mm(code)),
        }
    for p in papers:
        data["papers"].append({
            "code": p.code, "label": str(p.name), "labelDe": PAPER_LABEL_DE[p.code], "channel": p.channel,
            "caliperMm": f(p.caliper_mm), "table": p.spine_source == F.SPINE_SOURCE_TABLE,
            "minPages": p.min_pages, "maxPages": p.max_pages_for(F.BINDING_PAPERBACK),
        })
    offered = {p.code for p in papers}
    for fm in formats:
        data["formats"].append({
            "code": fm.code, "label": str(fm.name), "widthMm": f(fm.width_mm), "heightMm": f(fm.height_mm),
            "papers": {c: [p for p in fm.papers_for(c) if p in offered] for c in fm.channels},
        })

    js = "/* Generated by scripts/export_data.py - do not edit. */\nvar SPINE_DATA = " + json.dumps(
        data, ensure_ascii=False, separators=(",", ":")) + ";\n" \
        "if (typeof module !== 'undefined') module.exports = SPINE_DATA;\n"
    for target in (ROOT / "docs" / "data.js", ROOT / "extension" / "data.js"):
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(js, encoding="utf-8")

    vectors = []
    for fm in formats:
        for channel, codes in data["formats"][formats.index(fm)]["papers"].items():
            for code in codes:
                paper = F.get_paper(code)
                for pages in (paper.min_pages, 23, 48, 120, 220, 301, 500, min(868, paper.max_pages_for("paperback"))):
                    if pages < paper.min_pages:
                        continue
                    lay = F.cover_layout_mm(fm, pages, code, channel)
                    vectors.append({
                        "format": fm.code, "channel": channel, "paper": code, "pages": pages,
                        "spineMm": f(F.spine_width_mm(pages, code, channel)),
                        "coverWidthMm": f(lay["width_mm"]), "coverHeightMm": f(lay["height_mm"]),
                        "spineTextAllowed": lay["spine_text_allowed"],
                        "spineSafetyMm": f(lay["spine_safety_mm"]),
                    })
    (ROOT / "tests").mkdir(exist_ok=True)
    (ROOT / "tests" / "vectors.json").write_text(json.dumps(vectors, indent=1), encoding="utf-8")
    print(f"{len(papers)} papers, {len(formats)} formats, {len(vectors)} test vectors")


if __name__ == "__main__":
    main()
